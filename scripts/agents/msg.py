#!/usr/bin/env python3
"""Agent inbox tool (D-009). Single writer path for AGENTS/INBOX so the global MSG counter and the
open-message index never race when several agents post at once (file lock around every operation).

Usage (from repo root):
  python3 scripts/agents/msg.py send   --from CONTRACTS --to BACKEND_RELAYER --type request \
          --subject "ABI v1 ready" --body "..." [--body-file f.md] [--paths a,b]
  python3 scripts/agents/msg.py reply  MSG-007 --from CONTRACTS --body "Fixed in abc123" [--status answered|closed] [--paths ..]
  python3 scripts/agents/msg.py status MSG-007 --set answered|closed|open --by CONTRACTS [--note "fix commit abc123"]
  python3 scripts/agents/msg.py list   [--to ROLE] [--from ROLE] [--open]
  python3 scripts/agents/msg.py show   MSG-007

Types: question, request, fyi, blocker, answer.  Status: open, answered, closed.
Header written to the recipient inbox (AGENTS/INBOX/<TO>.md):
  ### [MSG-###] <ISO timestamp> FROM: <role> TO: <role> | type: <type> | status: <status>
"""
import argparse, datetime, fcntl, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
INBOX = os.path.join(ROOT, "AGENTS", "INBOX")
STATE = os.path.join(INBOX, ".state.json")
INDEX = os.path.join(INBOX, "_INDEX.md")
LOCK = os.path.join(INBOX, ".lock")

ROLES = ["ORCHESTRATOR", "ARCHITECT", "CONTRACTS", "CONTRACTS_QE", "BACKEND_RELAYER", "STREAMS_INFRA",
         "UI_DESIGN", "FRONTEND_INTEGRATION", "ATTRIBUTION_AI", "QE_E2E", "SECURITY_REVIEW", "DOCS_SUBMISSION"]
TYPES = ["question", "request", "fyi", "blocker", "answer"]
STATUSES = ["open", "answered", "closed"]
HEADER_RE = re.compile(r"^### \[(MSG-\d+)\] (\S+) FROM: (\S+) TO: (\S+) \| type: (\w+) \| status: (\w+)\s*$")


def now():
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def role(r):
    r = r.strip().upper()
    if r not in ROLES:
        sys.exit(f"unknown role {r!r}; valid: {', '.join(ROLES)}")
    return r


def load():
    if os.path.exists(STATE):
        return json.load(open(STATE))
    return {"counter": 0, "messages": {}}


def save(st):
    tmp = STATE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(st, f, indent=1)
        f.write("\n")
    os.replace(tmp, STATE)
    write_index(st)


def write_index(st):
    msgs = sorted(st["messages"].values(), key=lambda m: int(m["id"].split("-")[1]))
    open_ = [m for m in msgs if m["status"] == "open"]
    blockers = [m for m in open_ if m["type"] == "blocker"]
    L = ["# INBOX index",
         "_Generated by `scripts/agents/msg.py` (D-009). Don't edit by hand; use the script._", "",
         f"**Counter:** {st['counter']} · next id **MSG-{st['counter'] + 1:03d}** · "
         f"open: **{len(open_)}** · open blockers: **{len(blockers)}**", "",
         "## Open messages", "| ID | From → To | Type | Subject | Opened | Inbox |", "|---|---|---|---|---|---|"]
    L += [f"| {m['id']} | {m['from']} → {m['to']} | {'🟥 ' if m['type'] == 'blocker' else ''}{m['type']} | "
          f"{m['subject']} | {m['ts']} | `AGENTS/INBOX/{m['to']}.md` |" for m in open_] or ["| — | | | _none_ | | |"]
    L += ["", "## All messages", "| ID | Opened | From → To | Type | Status | Subject | Resolution |", "|---|---|---|---|---|---|---|"]
    L += [f"| {m['id']} | {m['ts']} | {m['from']} → {m['to']} | {m['type']} | {m['status']} | {m['subject']} | "
          f"{m.get('resolution', '')} |" for m in msgs]
    with open(INDEX, "w") as f:
        f.write("\n".join(L) + "\n")


def inbox_path(r):
    return os.path.join(INBOX, f"{r}.md")


def ensure_inbox(r):
    p = inbox_path(r)
    if not os.path.exists(p):
        with open(p, "w") as f:
            f.write(f"# INBOX — {r}\n_Messages addressed to {r}. Newest at the bottom. Post/answer via "
                    f"`scripts/agents/msg.py` (D-009)._\n")
    return p


def set_header_status(r, mid, status):
    p = ensure_inbox(r)
    lines = open(p).read().split("\n")
    for i, l in enumerate(lines):
        m = HEADER_RE.match(l)
        if m and m.group(1) == mid:
            lines[i] = re.sub(r"\| status: \w+\s*$", f"| status: {status}", l)
            break
    else:
        sys.exit(f"{mid} header not found in {p}")
    open(p, "w").write("\n".join(lines))


def append_note(r, mid, note):
    """Append a status note directly under the message block (before the next header)."""
    p = ensure_inbox(r)
    lines = open(p).read().rstrip("\n").split("\n")
    start = next(i for i, l in enumerate(lines) if (m := HEADER_RE.match(l)) and m.group(1) == mid)
    end = next((j for j in range(start + 1, len(lines)) if HEADER_RE.match(lines[j])), len(lines))
    while end > start + 1 and lines[end - 1].strip() in ("", "---"):
        end -= 1
    lines.insert(end, f"> {note}")
    open(p, "w").write("\n".join(lines) + "\n")


def do_send(st, frm, to, typ, subject, body, paths, re_id=None):
    if typ not in TYPES:
        sys.exit(f"bad type {typ}; valid: {TYPES}")
    st["counter"] += 1
    mid = f"MSG-{st['counter']:03d}"
    ts = now()
    block = [f"### [{mid}] {ts} FROM: {frm} TO: {to} | type: {typ} | status: open",
             f"**Subject:** {subject}" + (f" _(re: {re_id})_" if re_id else ""), "", body.strip()]
    if paths:
        block += ["", "**Paths:** " + ", ".join(f"`{p.strip()}`" for p in paths.split(",") if p.strip())]
    block += ["", "---", ""]
    with open(ensure_inbox(to), "a") as f:
        f.write("\n" + "\n".join(block))
    st["messages"][mid] = {"id": mid, "ts": ts, "from": frm, "to": to, "type": typ, "status": "open",
                           "subject": subject, "re": re_id}
    return mid


def do_status(st, mid, status, by, note):
    if mid not in st["messages"]:
        sys.exit(f"unknown {mid}")
    if status not in STATUSES:
        sys.exit(f"bad status {status}")
    m = st["messages"][mid]
    m["status"] = status
    if note:
        m["resolution"] = note
    set_header_status(m["to"], mid, status)
    append_note(m["to"], mid, f"status → **{status}** by {by} at {now()}" + (f": {note}" if note else ""))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    s = sp.add_parser("send"); s.add_argument("--from", dest="frm", required=True); s.add_argument("--to", required=True)
    s.add_argument("--type", required=True); s.add_argument("--subject", required=True)
    s.add_argument("--body", default=""); s.add_argument("--body-file"); s.add_argument("--paths", default="")
    r = sp.add_parser("reply"); r.add_argument("id"); r.add_argument("--from", dest="frm", required=True)
    r.add_argument("--body", default=""); r.add_argument("--body-file"); r.add_argument("--paths", default="")
    r.add_argument("--status", default="answered", choices=STATUSES)
    t = sp.add_parser("status"); t.add_argument("id"); t.add_argument("--set", required=True, choices=STATUSES)
    t.add_argument("--by", required=True); t.add_argument("--note", default="")
    l = sp.add_parser("list"); l.add_argument("--to"); l.add_argument("--from", dest="frm"); l.add_argument("--open", action="store_true")
    w = sp.add_parser("show"); w.add_argument("id")
    a = ap.parse_args()

    os.makedirs(INBOX, exist_ok=True)
    with open(LOCK, "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        st = load()
        if a.cmd in ("send", "reply"):
            body = open(a.body_file).read() if a.body_file else a.body
            if not body.strip():
                sys.exit("empty body (use --body or --body-file)")
            frm = role(a.frm)
            if a.cmd == "send":
                mid = do_send(st, frm, role(a.to), a.type.lower(), a.subject, body, a.paths)
            else:
                orig = st["messages"].get(a.id.upper()) or sys.exit(f"unknown {a.id}")
                mid = do_send(st, frm, orig["from"], "answer", f"Re: {orig['subject']}", body, a.paths, re_id=orig["id"])
                do_status(st, orig["id"], a.status, frm, f"see {mid}")
            save(st)
            print(mid)
        elif a.cmd == "status":
            do_status(st, a.id.upper(), a.set, role(a.by), a.note)
            save(st)
            print(f"{a.id.upper()} → {a.set}")
        elif a.cmd == "list":
            for m in sorted(st["messages"].values(), key=lambda m: int(m["id"].split("-")[1])):
                if a.to and m["to"] != role(a.to): continue
                if a.frm and m["from"] != role(a.frm): continue
                if a.open and m["status"] != "open": continue
                print(f"{m['id']}  {m['status']:8s} {m['type']:8s} {m['from']} → {m['to']}  {m['subject']}")
        elif a.cmd == "show":
            m = st["messages"].get(a.id.upper()) or sys.exit(f"unknown {a.id}")
            txt = open(inbox_path(m["to"])).read().split("\n")
            start = next(i for i, l in enumerate(txt) if (h := HEADER_RE.match(l)) and h.group(1) == m["id"])
            end = next((j for j in range(start + 1, len(txt)) if HEADER_RE.match(txt[j])), len(txt))
            print("\n".join(txt[start:end]).rstrip())


if __name__ == "__main__":
    main()
