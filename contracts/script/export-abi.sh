#!/usr/bin/env bash
# Regenerates packages/shared/src/abi/vouch.ts from the compiled Vouch contract (reproducible; no secrets).
#   - vouchAbi                 full ABI (as const, for viem type inference)
#   - VOUCH_EVENT_SIGNATURES   event name -> canonical signature
#   - VOUCH_EVENT_TOPICS       event name -> topic0 (from `forge inspect … events`)
#   - VOUCH_TYPE_STRINGS       EIP-712 type strings, extracted verbatim from src/libraries/VouchHash.sol
# Usage (repo root):  bash contracts/script/export-abi.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
export PATH="$HOME/.foundry/bin:$PATH"
cd "$ROOT/contracts"
# Production artifacts never depend on test/ (a broken test file must not block the export).
forge build --silent --skip test
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
forge inspect src/Vouch.sol:Vouch abi --json --skip test >"$TMP/abi.json"
forge inspect src/Vouch.sol:Vouch events --json --skip test >"$TMP/events.json"
OUT="$ROOT/packages/shared/src/abi/vouch.ts"
mkdir -p "$(dirname "$OUT")"
python3 -I - "$TMP/abi.json" "$TMP/events.json" src/libraries/VouchHash.sol "$OUT" <<'PY'
import json, re, sys
abi_path, events_path, hash_sol, out = sys.argv[1:5]
abi = json.load(open(abi_path))
events = json.load(open(events_path))
src = open(hash_sol).read()
types = {}
for m in re.finditer(r'keccak256\("([A-Za-z]+)\(([^"]*)\)"\)', src):
    types[m.group(1)] = f"{m.group(1)}({m.group(2)})"
sigs = {s.split('(')[0]: s for s in events}
topics = {s.split('(')[0]: t for s, t in events.items()}
def obj(d):
    return json.dumps(dict(sorted(d.items())), indent=2)
body = f"""// AUTO-GENERATED by contracts/script/export-abi.sh from contracts/src/Vouch.sol. DO NOT EDIT BY HAND.
// Regenerate after any contract change:  bash contracts/script/export-abi.sh

export const vouchAbi = {json.dumps(abi, indent=2)} as const;

/** Canonical event signatures (topic0 = keccak256(signature)). */
export const VOUCH_EVENT_SIGNATURES = {obj(sigs)} as const;

/** topic0 of every Vouch event — the Streams filter targets (filter by the Vouch address too). */
export const VOUCH_EVENT_TOPICS = {obj(topics)} as const;

/** EIP-712 type strings exactly as hashed in contracts/src/libraries/VouchHash.sol. */
export const VOUCH_TYPE_STRINGS = {obj(types)} as const;
"""
open(out, 'w').write(body)
print(f"wrote {out}: {sum(1 for x in abi if x['type']=='function')} functions, {len(topics)} events, {len(types)} EIP-712 types")
PY
